#!/usr/bin/env python3
"""Builds Support/{en,pl}.lproj/Localizable.strings from scripts/l10n/{en,pl}/*.py.

Layout
  scripts/l10n/keys.txt      lead file: every localizable literal in the Swift sources, as the
                             compiler extracts it (Text("…"), Button("…"), String(localized: "…") …)
                             plus the runtime keys looked up by L() / LocalizedStringKey(variable).
  scripts/l10n/en/<area>.py  English, STRINGS = {key: text}
  scripts/l10n/pl/<area>.py  Polish, same keys in the same area
  scripts/l10n/<lang>/_infoplist.py  permission prompts, written to InfoPlist.strings

The key is the literal itself (some areas were written in English, some in Polish), so the file of
the source language holds the key unchanged. Both languages must hold every key: nothing falls back
to the literal.

  gen_localization.py           write the .strings files (fails if en and pl areas differ)
  gen_localization.py --check   also rebuild keys.txt with the compiler and verify that
                                every lead key is in both languages, no key is stale and
                                the format specifiers (%@, %lld, %d, %%) match
  gen_localization.py --orphans list literals that look like UI text but are not localized
                                (exceptions: scripts/l10n/not_ui/*.txt,
                                one literal per line, interpolations written as %@)
"""
import glob, importlib.util, json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
L10N = os.path.join(HERE, "l10n")
LANGS = ("en", "pl")
# INTERMEZZO_LOC_CACHE: a separate build dir (parallel checks); keys.txt then goes there too.
CACHE = os.path.expanduser(os.environ.get("INTERMEZZO_LOC_CACHE", "~/.cache/intermezzo-loc"))
KEYS = os.path.join(CACHE, "keys.txt") if "INTERMEZZO_LOC_CACHE" in os.environ else os.path.join(L10N, "keys.txt")


def load_area(path):
    spec = importlib.util.spec_from_file_location("l10n_" + os.path.basename(path)[:-3], path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.STRINGS


def load():
    """{lang: {area: {key: text}}}"""
    return {lang: {os.path.basename(p)[:-3]: load_area(p)
                   for p in sorted(glob.glob(os.path.join(L10N, lang, "*.py")))}
            for lang in LANGS}


def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


INFO_PLIST_AREA = "_infoplist"   # en|pl/_infoplist.py -> InfoPlist.strings (permission prompts)


def write(lang, table, name="Localizable.strings"):
    d = os.path.join(ROOT, "Support", f"{lang}.lproj")
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, name), "w", encoding="utf-8") as f:
        f.write("/* Generated by scripts/gen_localization.py — edit scripts/l10n/<lang>/*.py instead. */\n")
        for k in sorted(table):
            f.write(f'"{esc(k)}" = "{esc(table[k])}";\n')


SPEC = re.compile(r"%(?:(\d+)\$)?(lld|ld|d|@|f|\.\d+f|%)")


def specs(s):
    """Argument types in argument order (%2$@ %1$lld reads as [lld, @]); %% is not an argument."""
    out, n = [], 0
    for index, kind in SPEC.findall(s):
        if kind == "%":
            continue
        n += 1
        out.append((int(index) if index else n, kind))
    return [kind for _, kind in sorted(out)]


def norm(k):
    """Key -> comparable form: every argument specifier becomes \\x02, %% becomes %."""
    k = k.replace("%%", "\x01")
    k = re.sub(r"%(?:\d+\$)?(?:lld|ld|d|@|f|\.\d+f)", "\x02", k)
    return k.replace("\x01", "%")


def swift_literals():
    """Every string literal in the sources, interpolations as \\x02."""
    out = set()
    for path in glob.glob(os.path.join(ROOT, "Sources", "**", "*.swift"), recursive=True):
        text = open(path, encoding="utf-8").read()
        for m in re.finditer(r'"((?:[^"\\]|\\.)*)"', text):
            out.add(collapse(m.group(1)))
    return out


def collapse(s):
    res, i = "", 0
    while i < len(s):
        if s.startswith("\\(", i):
            depth, j = 1, i + 2
            while j < len(s) and depth:
                depth += (s[j] == "(") - (s[j] == ")")
                j += 1
            res += "\x02"
            i = j
        else:
            res += s[i]
            i += 1
    res = res.replace("\\n", "\n").replace('\\"', '"').replace("\\\\", "\\")
    return norm(res)


def compiler_keys():
    """Localizable literals as the Swift compiler sees them (like Xcode's string extraction)."""
    out_dir = os.path.join(CACHE, "out")
    # A fresh build each time: an up-to-date build compiles nothing and so extracts nothing.
    subprocess.run(["rm", "-rf", out_dir, os.path.join(CACHE, "build")], check=True)
    os.makedirs(out_dir)
    cmd = ["swift", "build", "-c", "release", "--scratch-path", os.path.join(CACHE, "build"),
           "-Xswiftc", "-emit-localized-strings", "-Xswiftc", "-emit-localized-strings-path",
           "-Xswiftc", out_dir]
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit("swift build failed:\n" + r.stdout[-3000:] + r.stderr[-3000:])
    keys = {}
    for f in glob.glob(os.path.join(out_dir, "*.stringsdata")):
        data = json.load(open(f))
        for e in data["tables"].get("Localizable", []):
            src = os.path.relpath(data["source"], os.path.join(ROOT, "Sources"))
            line = e.get("location", {}).get("startingLine", "?")   # absent for some generated keys
            keys.setdefault(e["key"], f"{src}:{line}")
    return keys


def check(tables):
    merged = {lang: {k: v for area in tables[lang].values() for k, v in area.items()} for lang in LANGS}
    comp = compiler_keys()
    lits = swift_literals()
    runtime = sorted(k for k in merged["en"] if k not in comp and norm(k) in lits)
    stale = sorted(k for k in merged["en"] if k not in comp and norm(k) not in lits)
    with open(KEYS, "w", encoding="utf-8") as f:
        f.write("# Lead file, generated by gen_localization.py --check. Do not edit.\n")
        f.write("# compiler: localizable literals in the sources; runtime: looked up by L() / LocalizedStringKey(value).\n")
        for k in sorted(comp):
            f.write(f"compiler\t{comp[k]}\t{esc(k)}\n")
        for k in runtime:
            f.write(f"runtime\t-\t{esc(k)}\n")
    problems = 0
    for lang in LANGS:
        for k in sorted(comp):
            if k not in merged[lang]:
                print(f"MISSING {lang}: {k[:100]!r}  ({comp[k]})")
                problems += 1
    for k in stale:
        print(f"STALE (not in the sources): {k[:100]!r}")
        problems += 1
    for lang in LANGS:
        for k, v in merged[lang].items():
            if specs(k) != specs(v):
                print(f"FORMAT {lang}: {k[:70]!r} -> {v[:70]!r}")
                problems += 1
    print(f"lead: {len(comp)} compiler + {len(runtime)} runtime keys; {problems} problems")
    return problems


NOT_UI_LINE = re.compile(
    r"Trace\.log|LightLog\.(event|detail)|\blog\.(debug|info|error|notice|warning|fault)|print\(|NSLog\(|Logger\(|fatalError|"
    r"assert|precondition|forKey|UserDefaults|#Predicate|systemName:|Image\(|NSImage\(|URL\(|"
    r"kindRaw|case \w+ = \"|Notification\.Name|identifier|DispatchQueue\(label")


def orphans():
    lead = {}
    path = KEYS
    if os.path.exists(path):
        for line in open(path, encoding="utf-8"):
            if not line.startswith("#"):
                lead[norm(line.rstrip("\n").split("\t", 2)[2].replace("\\n", "\n").replace('\\"', '"'))] = 1
    allowed = set()
    for allow_path in glob.glob(os.path.join(L10N, "not_ui", "*.txt")):
        allowed |= {l.rstrip("\n") for l in open(allow_path, encoding="utf-8") if l.strip() and not l.startswith("#")}
    found = 0
    for p in sorted(glob.glob(os.path.join(ROOT, "Sources", "**", "*.swift"), recursive=True)):
        rel = os.path.relpath(p, os.path.join(ROOT, "Sources"))
        for i, line in enumerate(open(p, encoding="utf-8"), 1):
            s = line.strip()
            if s.startswith("//") or NOT_UI_LINE.search(line):
                continue
            for m in re.finditer(r'"((?:[^"\\]|\\.)*)"', line):
                k = collapse(m.group(1))
                bare = k.replace("\x02", "")
                if not re.search(r"[A-Za-ząćęłńóśźżĄĆĘŁŃÓŚŹŻ]{3}", bare):
                    continue
                if " " not in k.strip() and not re.search("[ąćęłńóśźżĄĆĘŁŃÓŚŹŻ]", k) and not k[:1].isupper():
                    continue
                if re.fullmatch(r"[a-z0-9._-]+", k) or norm(k) in lead or k.replace("\x02", "%@") in allowed:
                    continue
                print(f"{rel}:{i}: {k.replace(chr(2), '%@')[:110]}")
                found += 1
    print(f"{found} possible unlocalized literals")


def main():
    tables = load()
    bad = 0
    for area in sorted(set(tables["en"]) | set(tables["pl"])):
        en, pl = tables["en"].get(area, {}), tables["pl"].get(area, {})
        for k in en.keys() - pl.keys():
            print(f"ONLY IN en/{area}.py: {k[:100]!r}")
            bad += 1
        for k in pl.keys() - en.keys():
            print(f"ONLY IN pl/{area}.py: {k[:100]!r}")
            bad += 1
    seen = {}
    for area, items in tables["en"].items():
        for k in items:
            if k in seen:
                print(f"DUPLICATE key in {seen[k]} and {area}: {k[:80]!r}")
                bad += 1
            seen[k] = area
    plist = open(os.path.join(ROOT, "Support", "Info.plist"), encoding="utf-8").read()
    for k in tables["en"].get(INFO_PLIST_AREA, {}):
        if f"<key>{k}</key>" not in plist:
            print(f"NOT IN Info.plist: {k}")
            bad += 1
    for lang in LANGS:
        write(lang, tables[lang].pop(INFO_PLIST_AREA, {}), "InfoPlist.strings")
        write(lang, {k: v for area in tables[lang].values() for k, v in area.items()})
    print("keys per language: " + ", ".join(f"{lang} {sum(map(len, tables[lang].values()))}" for lang in LANGS))
    if "--check" in sys.argv:
        bad += check(tables)
    if "--orphans" in sys.argv:
        orphans()
    sys.exit(1 if bad else 0)


main()
